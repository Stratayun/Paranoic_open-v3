/** Each result belongs to this exact input; changing the password clears the old verdict immediately. */
@Composable
fun rememberPasswordAssessment(core: CoreGateway, password: String): CoreResult<PasswordFeedback>? {
    var assessment by remember(core, password) { mutableStateOf<CoreResult<PasswordFeedback>?>(null) }
    LaunchedEffect(core, password) {
        if (password.isNotEmpty()) {
            assessment = try {
                val result = core.passwordFeedback(password)
                currentCoroutineContext().ensureActive()
                result
            } catch (cancelled: CancellationException) { throw cancelled }
            catch (_: Exception) { CoreResult.Failure(CoreFault.Unavailable) }
        }
    }
    return assessment
}

fun CoreResult<PasswordFeedback>?.acceptsPassword(): Boolean =
    (this as? CoreResult.Value<PasswordFeedback>)?.value?.strength?.let { it != PasswordStrength.Weak } == true

/** Rust owns the password policy; this form displays its assessment and generation result. */
@Composable
fun PasswordTools(core: CoreGateway, password: String, enabled: Boolean = true,
    assessment: CoreResult<PasswordFeedback>? = rememberPasswordAssessment(core, password),
    onGenerated: (String) -> Unit): PasswordStrength? {
    var generated by remember(core) { mutableStateOf<String?>(null) }
    var generationFault by remember(core) { mutableStateOf<CoreFault?>(null) }
    var generating by remember(core) { mutableStateOf(false) }
    val scope = rememberCoroutineScope()
    DisposableEffect(core) { onDispose { generated = null } }
    val scheme = MaterialTheme.colorScheme
    Column(verticalArrangement = Arrangement.spacedBy(2.dp)) {
        Text(tr("От 12 символов. Лучше фраза из нескольких слов — её легче запомнить.",
            "12 characters or more. A phrase of several words is easier to remember."),
            style = MaterialTheme.typography.bodySmall)
        if (password.isNotEmpty()) when (val result = assessment) {
            null -> Text(tr("Проверяем пароль…", "Checking password…"), style = MaterialTheme.typography.bodySmall)
            is CoreResult.Failure -> FaultNotice(result.fault)
            is CoreResult.Value -> {
                val feedback = result.value
                Text(when (feedback.strength) {
                    PasswordStrength.Weak -> tr("Пока не подходит", "Not acceptable yet")
                    PasswordStrength.Fair -> tr("Подходит. Можно усилить по подсказкам ниже.", "Acceptable. Follow the hints below to strengthen it.")
                    PasswordStrength.Strong -> tr("Надёжный пароль", "Strong password")
                }, style = MaterialTheme.typography.labelLarge,
                    color = if (result.acceptsPassword()) scheme.primary else scheme.onSurfaceVariant)
                feedback.hints.forEach { hint ->
                    Text(when (hint) {
                        PasswordHint.TooShort -> tr("Нужно не менее 12 символов.", "Use at least 12 characters.")
                        PasswordHint.Common -> tr("Содержит распространённый пароль — замените эту часть.", "Contains a common password — replace that part.")
                        PasswordHint.Repeats -> tr("Есть повторы символов.", "Contains repeated characters.")
                        PasswordHint.Sequence -> tr("Есть последовательность вроде 1234 или abcd.", "Contains a run such as 1234 or abcd.")
                        PasswordHint.OneKind -> tr("Один вид символов: удлините фразу или добавьте цифру либо заглавную.", "One kind of character: make it longer or add a digit or capital.")
                        PasswordHint.AddWord -> tr("Добавьте ещё слово — станет надёжнее.", "Add another word to make it stronger.")
                    }, style = MaterialTheme.typography.bodySmall)
                }
            }
        }
        TextButton(enabled = enabled && core.connected && !generating, onClick = {
            generating = true; generationFault = null
            scope.launch {
                try {
                    val result = core.generatePassphrase(6)
                    currentCoroutineContext().ensureActive()
                    when (result) {
                        is CoreResult.Value -> generated = result.value
                        is CoreResult.Failure -> generationFault = result.fault
                    }
                } catch (cancelled: CancellationException) { throw cancelled }
                catch (_: Exception) { generationFault = CoreFault.Unavailable }
                finally { generating = false }
            }
        }) { Text(if (generating) tr("Создаём…", "Generating…") else tr("Сгенерировать пароль", "Generate a password")) }
        generationFault?.let { FaultNotice(it) }
    }
    generated?.let { value ->
        AlertDialog(modifier = Modifier.trackSecretActivity(), onDismissRequest = { generated = null },
            title = { Text(tr("Случайный пароль", "Random password")) },
            text = { Column(Modifier.heightIn(max = 420.dp).verticalScroll(rememberScrollState()),
                verticalArrangement = Arrangement.spacedBy(12.dp)) {
                Text(tr("Запомните или запишите его в безопасном месте отдельно от устройства. Приложение не сохраняет его и не копирует в буфер.",
                    "Remember it or write it down somewhere safe, separately from this device. The app does not store or copy it."))
                // Deliberately not selectable and not a clipboard/live-region value.
                Text(value, fontFamily = FontFamily.Monospace, style = MaterialTheme.typography.titleLarge)
                Text(tr("После подстановки повторите пароль самостоятельно.", "After applying it, type the password again to confirm."))
            } },
            confirmButton = { TextButton(enabled = enabled, onClick = { generated = null; onGenerated(value) }) {
                Text(tr("Использовать", "Use"))
            } },
            dismissButton = { TextButton(onClick = { generated = null }) { Text(tr("Закрыть", "Close")) } })
    }
    return (assessment as? CoreResult.Value<PasswordFeedback>)?.value?.strength
}
