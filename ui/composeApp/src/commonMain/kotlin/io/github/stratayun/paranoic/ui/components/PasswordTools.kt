/** Rust owns analysis, randomness and word lists. Secrets live only in this form. */
@Composable
fun PasswordTools(core: CoreGateway, password: String, enabled: Boolean = true,
    onGenerated: (String) -> Unit): PasswordStrength? {
    // A changed password must not inherit the previous password's assessment,
    // even for the frame before LaunchedEffect starts.
    var feedback by remember(core, password) { mutableStateOf<PasswordFeedback?>(null) }
    var analysisFault by remember(core, password) { mutableStateOf<CoreFault?>(null) }
    var generated by remember(core) { mutableStateOf<String?>(null) }
    var generationFault by remember(core) { mutableStateOf<CoreFault?>(null) }
    var generating by remember(core) { mutableStateOf(false) }
    val scope = rememberCoroutineScope()
    LaunchedEffect(core, password) {
        if (password.isEmpty()) return@LaunchedEffect
        delay(250)
        try {
            val result = core.passwordFeedback(password)
            currentCoroutineContext().ensureActive()
            when (result) {
                is CoreResult.Value -> feedback = result.value
                is CoreResult.Failure -> analysisFault = result.fault
            }
        } catch (cancelled: CancellationException) { throw cancelled }
        catch (_: Exception) { analysisFault = CoreFault.Unavailable }
    }
    DisposableEffect(core) { onDispose { generated = null; feedback = null } }
    Column(verticalArrangement = Arrangement.spacedBy(4.dp)) {
        if (password.isNotEmpty()) {
            val assessment = feedback
            Text(when (assessment?.strength) {
                PasswordStrength.Weak -> tr("Слабый пароль", "Weak password")
                PasswordStrength.Fair -> tr("Допустимый пароль", "Acceptable password")
                PasswordStrength.Strong -> tr("Надёжный пароль", "Strong password")
                null -> if (analysisFault == null) tr("Оцениваем пароль…", "Checking password…")
                    else tr("Оценка пароля недоступна.", "Password assessment is unavailable.")
            }, style = MaterialTheme.typography.bodySmall)
            assessment?.hints?.forEach { hint -> Text(hint.label(), style = MaterialTheme.typography.bodySmall) }
            analysisFault?.let { FaultNotice(it) }
        }
        TextButton(enabled = enabled && core.connected && !generating, onClick = {
            generating = true; generationFault = null
            scope.launch {
                try {
                    val result = core.generatePassphrase(6)
                    currentCoroutineContext().ensureActive()
                    when (result) {
                        is CoreResult.Value -> generated = result.value
                        is CoreResult.Failure -> generationFault = result.fault
                    }
                } catch (cancelled: CancellationException) { throw cancelled }
                catch (_: Exception) { generationFault = CoreFault.Unavailable }
                finally { generating = false }
            }
        }) { Text(if (generating) tr("Создаём фразу…", "Generating phrase…") else tr("Придумать фразу", "Generate a phrase")) }
        generationFault?.let { FaultNotice(it) }
    }
    generated?.let { phrase ->
        AlertDialog(modifier = Modifier.trackSecretActivity(), onDismissRequest = { generated = null },
            title = { Text(tr("Шесть случайных слов", "Six random words")) },
            text = { Column(Modifier.heightIn(max = 420.dp).verticalScroll(rememberScrollState()),
                verticalArrangement = Arrangement.spacedBy(12.dp)) {
                Text(tr("Запомните или запишите фразу в безопасном месте отдельно от устройства. Приложение не сохраняет её и не предлагает копирование.",
                    "Remember the phrase or record it somewhere safe, separately from this device. The app does not store it or offer copying."))
                // Deliberately not selectable and not a clipboard/live-region value.
                Text(phrase, fontFamily = FontFamily.Monospace, style = MaterialTheme.typography.titleMedium)
                Text(tr("После подстановки повторите пароль самостоятельно.", "After applying it, type the password again to confirm."))
            } },
            confirmButton = { TextButton(enabled = enabled, onClick = { generated = null; onGenerated(phrase) }) {
                Text(tr("Использовать фразу", "Use phrase"))
            } },
            dismissButton = { TextButton(onClick = { generated = null }) { Text(tr("Закрыть", "Close")) } })
    }
    return feedback?.strength
}

@Composable
private fun PasswordHint.label(): String = when (this) {
    PasswordHint.TooShort -> tr("Сделайте пароль длиннее.", "Make the password longer.")
    PasswordHint.Common -> tr("Этот пароль слишком распространён. Выберите уникальный.", "This password is too common. Choose a unique one.")
    PasswordHint.Repeats -> tr("Избегайте повторения одинаковых частей.", "Avoid repeating the same parts.")
    PasswordHint.Sequence -> tr("Избегайте последовательностей букв, цифр и клавиш.", "Avoid sequences of letters, digits or keys.")
    PasswordHint.OneKind -> tr("Используйте разные слова и виды символов.", "Use varied words and character types.")
    PasswordHint.AddWord -> tr("Добавьте ещё одно случайное слово.", "Add another random word.")
}
