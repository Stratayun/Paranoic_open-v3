/**
 * Owner's rule (25.11.2026), the same as Rust `password_strength`: at least 8
 * characters with a lowercase letter, an uppercase letter, a digit and a
 * symbol, and no well-known password inside. Strong from 12 characters.
 */
object PasswordRule {
    const val MIN = 8
    const val STRONG = 12
    private val common = listOf("password", "passw0rd", "qwerty", "123456", "111111", "letmein", "admin", "welcome",
        "iloveyou", "monkey", "dragon", "пароль", "йцукен", "qwertyuiop", "abc123", "000000")
    fun long(p: String) = p.length >= MIN
    fun lower(p: String) = p.any { it.isLowerCase() }
    fun upper(p: String) = p.any { it.isUpperCase() }
    fun digit(p: String) = p.any { it in '0'..'9' }
    fun symbol(p: String) = p.any { !it.isLetterOrDigit() }
    fun common(p: String) = p.lowercase().let { lower -> common.any { it in lower } }
    fun strength(p: String): PasswordStrength = when {
        !long(p) || common(p) || !lower(p) || !upper(p) || !digit(p) || !symbol(p) -> PasswordStrength.Weak
        p.length >= STRONG -> PasswordStrength.Strong
        else -> PasswordStrength.Fair
    }
    fun acceptable(p: String) = strength(p) != PasswordStrength.Weak
}

/** Checklist under a new-password field plus a random password generator. Secrets live only in this form. */
@Composable
fun PasswordTools(core: CoreGateway, password: String, enabled: Boolean = true,
    onGenerated: (String) -> Unit): PasswordStrength? {
    var generated by remember(core) { mutableStateOf<String?>(null) }
    var generationFault by remember(core) { mutableStateOf<CoreFault?>(null) }
    var generating by remember(core) { mutableStateOf(false) }
    val scope = rememberCoroutineScope()
    DisposableEffect(core) { onDispose { generated = null } }
    val scheme = MaterialTheme.colorScheme
    Column(verticalArrangement = Arrangement.spacedBy(2.dp)) {
        @Composable fun Check(ok: Boolean, label: String) = Row(verticalAlignment = Alignment.CenterVertically) {
            Text(if (ok) "✓" else "•", Modifier.width(20.dp), color = if (ok) scheme.primary else scheme.onSurfaceVariant)
            Text(label, style = MaterialTheme.typography.bodySmall, color = if (ok) scheme.onSurface else scheme.onSurfaceVariant)
        }
        Check(PasswordRule.long(password), tr("Не короче ${PasswordRule.MIN} символов", "At least ${PasswordRule.MIN} characters"))
        Check(PasswordRule.lower(password) && PasswordRule.upper(password), tr("Строчные и заглавные буквы", "Lowercase and uppercase letters"))
        Check(PasswordRule.digit(password), tr("Цифра", "A digit"))
        Check(PasswordRule.symbol(password), tr("Символ (!, #, пробел…)", "A symbol (!, #, space…)"))
        if (password.isNotEmpty() && PasswordRule.common(password))
            Text(tr("Содержит распространённый пароль — замените эту часть.", "Contains a common password — replace that part."),
                style = MaterialTheme.typography.bodySmall, color = scheme.error)
        if (password.isNotEmpty()) Text(when (PasswordRule.strength(password)) {
            PasswordStrength.Weak -> tr("Пока не подходит", "Not acceptable yet")
            PasswordStrength.Fair -> tr("Подходит. Длиннее ${PasswordRule.STRONG} символов — надёжнее.", "Acceptable. ${PasswordRule.STRONG}+ characters is stronger.")
            PasswordStrength.Strong -> tr("Надёжный пароль", "Strong password")
        }, style = MaterialTheme.typography.labelLarge,
            color = if (PasswordRule.acceptable(password)) scheme.primary else scheme.onSurfaceVariant)
        TextButton(enabled = enabled && core.connected && !generating, onClick = {
            generating = true; generationFault = null
            scope.launch {
                try {
                    val result = core.generatePassphrase(6)
                    currentCoroutineContext().ensureActive()
                    when (result) {
                        is CoreResult.Value -> generated = result.value
                        is CoreResult.Failure -> generationFault = result.fault
                    }
                } catch (cancelled: CancellationException) { throw cancelled }
                catch (_: Exception) { generationFault = CoreFault.Unavailable }
                finally { generating = false }
            }
        }) { Text(if (generating) tr("Создаём…", "Generating…") else tr("Сгенерировать пароль", "Generate a password")) }
        generationFault?.let { FaultNotice(it) }
    }
    generated?.let { value ->
        AlertDialog(modifier = Modifier.trackSecretActivity(), onDismissRequest = { generated = null },
            title = { Text(tr("Случайный пароль", "Random password")) },
            text = { Column(Modifier.heightIn(max = 420.dp).verticalScroll(rememberScrollState()),
                verticalArrangement = Arrangement.spacedBy(12.dp)) {
                Text(tr("Запомните или запишите его в безопасном месте отдельно от устройства. Приложение не сохраняет его и не копирует в буфер.",
                    "Remember it or write it down somewhere safe, separately from this device. The app does not store or copy it."))
                // Deliberately not selectable and not a clipboard/live-region value.
                Text(value, fontFamily = FontFamily.Monospace, style = MaterialTheme.typography.titleLarge)
                Text(tr("После подстановки повторите пароль самостоятельно.", "After applying it, type the password again to confirm."))
            } },
            confirmButton = { TextButton(enabled = enabled, onClick = { generated = null; onGenerated(value) }) {
                Text(tr("Использовать", "Use"))
            } },
            dismissButton = { TextButton(onClick = { generated = null }) { Text(tr("Закрыть", "Close")) } })
    }
    return if (password.isEmpty()) null else PasswordRule.strength(password)
}
